#!/usr/bin/env python3
"""Deterministic self-contained runtime for the fixed Stage 3A catalogue."""
from pathlib import Path
import hashlib,json,re,runpy
ROOT=Path(__file__).resolve().parents[1]
FOLDER=ROOT/'research/corner-prototype'
check=runpy.run_path(str(ROOT/'research/check-corner-certificate.py'))
examples=json.loads((FOLDER/'examples.json').read_text())
certificates={};digests={}
for entry in examples:
    raw=(FOLDER/entry['url']).read_bytes();c=json.loads(raw)
    assert check['validate'](c)==entry['counts']
    certificates[entry['id']]=c;digests[entry['id']]=hashlib.sha256(raw).hexdigest()
sources={}
for key in ['kernel','project','offline','app']:
    text=(FOLDER/(key+'.mjs')).read_text()
    text=re.sub(r'^import .*?;\s*\n','',text,flags=re.M)
    sources[key]=re.sub(r'\bexport (?=(const|function|class|async function)\b)','',text)
template=(FOLDER/'index.html').read_text().replace('<link rel="stylesheet" href="style.css">','<!--CORNER_STYLE-->')
template=template.replace('<script type="module" src="app.mjs"></script>','<!--CORNER_RUNTIME-->')
template=re.sub(r'<footer>.*?</footer>','<footer>Self-contained editable corner project · nine certified examples · physical constructibility unverified.</footer>',template,flags=re.S)
bundle={'catalogue':{'id':'corner-nine-v1','examples':examples,'certificates':certificates,'digests':digests},
        'sources':sources,'template':template,'css':(FOLDER/'style.css').read_text()}
(FOLDER/'bundle.mjs').write_text('// Generated by research/build-corner-package.py; edit source modules instead.\nexport const BUNDLE='+json.dumps(bundle,separators=(',',':'))+';\n')
print('Bundled and independently checked',len(examples),'constructions')
