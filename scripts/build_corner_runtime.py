"""Generate the trusted application runtime; no research-page UI is embedded."""
from pathlib import Path
import hashlib,json,re,runpy
ROOT=Path(__file__).resolve().parents[1]
folder=ROOT/'research/corner-prototype'
checker=runpy.run_path(str(ROOT/'research/check-corner-certificate.py'))
entries=json.loads((folder/'family.json').read_text());certs={};digests={}
for e in entries:
 raw=(folder/e['url']).read_bytes();c=json.loads(raw)
 assert checker['validate'](c)==e['counts']
 certs[e['id']]=c;digests[e['id']]=hashlib.sha256(raw).hexdigest()
catalogue=dict(id='corner-family-v2',legacyIds=[e['id'] for e in json.loads((folder/'examples.json').read_text())],examples=entries,certificates=certs,digests=digests,matrix=json.loads((folder/'family-matrix.json').read_text()))
sources=[]
for p in [folder/'kernel.mjs',folder/'project.mjs',folder/'render.mjs',ROOT/'corner-model.mjs']:
 s=re.sub(r'^import .*?;\s*\n','',p.read_text(),flags=re.M)
 sources.append(re.sub(r'\bexport (?=(const|function|class|async function)\b)','',s))
text='// Generated by scripts/build_corner_runtime.py; trusted model data and shared renderer.\n(function(){\n'+ '\n'.join(sources)+'\nwindow.MadWeaveCornerCore={Diagram,Project,CornerProject,createRenderer,id,number,catalogue:'+json.dumps(catalogue,separators=(',',':'))+'};\n})();\n'
(ROOT/'corner-runtime.js').write_text(text)
print('Built integrated runtime:',len(entries),'certificates,',len(text.encode()),'bytes')
