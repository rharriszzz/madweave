"""Generate the trusted application runtime; no research-page UI is embedded."""
from pathlib import Path
import base64,gzip,hashlib,json,re,runpy
ROOT=Path(__file__).resolve().parents[1]
folder=ROOT/'research/corner-prototype'
def write_runtime(nodes,root):
 sources=[]
 for p in [folder/'kernel.mjs',folder/'project.mjs',folder/'render.mjs',ROOT/'corner-model.mjs']:
  s=re.sub(r'^import .*?;\s*\n','',p.read_text(),flags=re.M)
  sources.append(re.sub(r'\bexport (?=(const|function|class|async function)\b)','',s))
 data=base64.b64encode(gzip.compress(json.dumps(nodes,separators=(',',':')).encode(),compresslevel=9,mtime=0)).decode()
 text='// Generated by scripts/build_corner_runtime.py; trusted model data and shared renderer.\n(function(){\n'+ '\n'.join(sources)+'\nwindow.MadWeaveCornerReady=(async()=>{\nconst bytes=Uint8Array.from(atob("'+data+'"),c=>c.charCodeAt(0));\nconst nodes=JSON.parse(await new Response(new Blob([bytes]).stream().pipeThrough(new DecompressionStream("gzip"))).text());\nconst dereference=v=>Array.isArray(v)?nodes[v[0]]:v;\nfor(let i=0;i<nodes.length;i++){const n=nodes[i];nodes[i]=Array.isArray(n)?n.map(dereference):Object.fromEntries(Object.entries(n).map(([k,v])=>[k,dereference(v)]));}\nreturn window.MadWeaveCornerCore={Diagram,Project,CornerProject,createRenderer,id,number,catalogue:nodes['+str(root)+']};\n})();\n})();\n'
 (ROOT/'corner-runtime.js').write_text(text)
 return len(text.encode())


def main():
 checker=runpy.run_path(str(ROOT/'research/check-corner-certificate.py'))
 entries=json.loads((folder/'family.json').read_text());certs={};digests={}
 for e in entries:
  raw=(folder/e['url']).read_bytes();c=json.loads(raw)
  assert checker['validate'](c)==e['counts']
  certs[e['id']]=c;digests[e['id']]=hashlib.sha256(raw).hexdigest()
 matrix=json.loads((folder/'family-matrix.json').read_text())
 # Use the existing producer, partitioner and independent checker. No browser
 # implementation of strip clipping, seam joining or construction is needed.
 family=runpy.run_path(str(ROOT/'research/build-corner-family.py'))
 widths=['100/107','100/133','5/9','1/3']
 sizes=list(range(1,9))
 original_rows=matrix['rows'][:]
 for row in original_rows:row['width']='3/4'
 for size in sizes:matrix['domain']['crops'].append(dict(id='s'+str(size),radius=str((3*size+1)//2),label='Size '+str(size)))
 cache=ROOT/'research/output/strip-ends-certificates';cache.mkdir(parents=True,exist_ok=True)
 source_digest=hashlib.sha256(b''.join((ROOT/path).read_bytes() for path in ['research/corner-crop-reference.py','research/single-corner-stage1.py','research/build-corner-family.py','research/check-corner-certificate.py'])).hexdigest()[:16]
 for phase in family['PHASES']:
  for size in sizes:
   for beta in matrix['domain']['angles']:
    template=next(r for r in original_rows if r['phase']==phase['id'] and r['beta']==beta and r['crop'] in phase['crops'])
    for spacing,width in enumerate(widths):
     key=f"{phase['id']}-{beta}-s{size}-sep{spacing}"
     row=dict(phase=phase['id'],weave=phase['weave'],crop='s'+str(size),beta=beta,width=width)
     matrix['rows'].append(row)
     if template['status']!='Validated':
      row.update(status=template['status'],witness=template['witness']);continue
     path=cache/(source_digest+'-'+key+'.json')
     if path.exists():c=json.loads(path.read_text())
     else:
      p=family['parameters'](phase,dict(radius=str((3*size+1)//2)),beta)
      p.update(W_over_P=width,end_style='strip',size=size)
      c=family['encode'](family['producer']['make'](p,key))
      c['render_cells'],c['render_outside_cells']=family['partition'](c['parameters'])
     counts=checker['validate'](c)
     raw=json.dumps(c,separators=(',',':'));path.write_text(raw)
     certs[key]=c;digests[key]=hashlib.sha256(raw.encode()).hexdigest()
     config={k:row[k] for k in ['weave','phase','crop','beta']}
     entries.append(dict(id=key,label=f"Size {size} · {counts['open_strips']} strips · {beta}°",counts=counts,default_pattern=None,config=config))
     row.update(id=key,status='Validated',parameters=c['parameters'])
   print('Built strip ends:',phase['id'],'size',size,flush=True)
 catalogue=dict(id='corner-family-v2',legacyIds=[e['id'] for e in json.loads((folder/'examples.json').read_text())],examples=entries,certificates=certs,digests=digests,matrix=matrix,widths=widths,sizes=sizes)
 # Share identical JSON subtrees (especially sector polygons across angles).
 # Children precede parents; references are one-element arrays in this table.
 nodes=[];interned={}
 def intern(value):
  if not isinstance(value,(dict,list)):return value
  encoded={k:intern(v) for k,v in value.items()} if isinstance(value,dict) else [intern(v) for v in value]
  key=json.dumps(encoded,separators=(',',':'))
  if key not in interned:interned[key]=len(nodes);nodes.append(encoded)
  return [interned[key]]
 root=intern(catalogue)[0]
 size=write_runtime(nodes,root)
 print("Built integrated runtime:",len(entries),"certificates,",size,"bytes")


if __name__=="__main__":main()
